-- Oil Shop Management Software — SQLite schema
-- Matches OilShop.Core models. Create with: sqlite3 oilshop.db < Schema.sql
-- (The app also creates the database automatically via EnsureCreatedAsync.)

PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS ShopSettings (
    Id INTEGER PRIMARY KEY,
    ShopName TEXT NOT NULL DEFAULT 'Roonjha Oil Traders',
    ShopAddress TEXT NOT NULL DEFAULT 'Main Market Road Lahore Punjab Pakistan',
    PhoneNumber TEXT NOT NULL DEFAULT '03001234567',
    ContactNumber TEXT NOT NULL DEFAULT '03001234567',
    EmailAddress TEXT NOT NULL DEFAULT 'info@roonjha.com',
    TaxRegistrationNumber TEXT NOT NULL DEFAULT 'NTN 1234567',
    ThemeColor TEXT NOT NULL DEFAULT 'Navy Blue',
    LogoPath TEXT,
    InvoiceHeaderText TEXT NOT NULL DEFAULT 'Roonjha Developers Oil Shop',
    ReceiptFooterText TEXT NOT NULL DEFAULT 'Thank you for visiting Roonjha Oil Traders',
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Customers (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT NOT NULL, Phone TEXT NOT NULL, Address TEXT, Email TEXT, NTN TEXT,
    BalanceDue DECIMAL(18,2) NOT NULL DEFAULT 0,
    Advance DECIMAL(18,2) NOT NULL DEFAULT 0,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Suppliers (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT NOT NULL, Phone TEXT NOT NULL, Address TEXT, Email TEXT, NTN TEXT,
    BalanceDue DECIMAL(18,2) NOT NULL DEFAULT 0,
    Advance DECIMAL(18,2) NOT NULL DEFAULT 0,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Products (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT NOT NULL, Category TEXT, Unit TEXT NOT NULL DEFAULT 'Liters',
    SalePrice DECIMAL(18,2) NOT NULL DEFAULT 0,
    PurchasePrice DECIMAL(18,2) NOT NULL DEFAULT 0,
    StockQuantity DECIMAL(18,2) NOT NULL DEFAULT 0,
    LowStockAlert DECIMAL(18,2) NOT NULL DEFAULT 10,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Roles (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Name TEXT NOT NULL, Description TEXT,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS RolePermissions (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    RoleId INTEGER NOT NULL REFERENCES Roles(Id) ON DELETE CASCADE,
    Module TEXT NOT NULL, Allowed INTEGER NOT NULL DEFAULT 0,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Staff (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    EmployeeId TEXT NOT NULL UNIQUE, Name TEXT NOT NULL, Designation TEXT NOT NULL,
    Department TEXT NOT NULL, JoiningDate TEXT NOT NULL, ContactNumber TEXT NOT NULL,
    Address TEXT, Salary DECIMAL(18,2) NOT NULL DEFAULT 0,
    IsActive INTEGER NOT NULL DEFAULT 1, OnLeave INTEGER NOT NULL DEFAULT 0,
    PhotoPath TEXT, RoleId INTEGER NOT NULL REFERENCES Roles(Id),
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Attendances (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    StaffId INTEGER NOT NULL REFERENCES Staff(Id) ON DELETE CASCADE,
    Date TEXT NOT NULL, CheckInTime TEXT, CheckOutTime TEXT,
    Status TEXT NOT NULL DEFAULT 'Present',
    InvoicesGenerated INTEGER NOT NULL DEFAULT 0,
    SalesMade DECIMAL(18,2) NOT NULL DEFAULT 0,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS SalesInvoices (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    InvoiceNumber TEXT NOT NULL UNIQUE, Date TEXT NOT NULL,
    CustomerId INTEGER NOT NULL REFERENCES Customers(Id),
    StaffId INTEGER REFERENCES Staff(Id),
    PaymentMode INTEGER NOT NULL DEFAULT 0,
    SubTotal DECIMAL(18,2) NOT NULL DEFAULT 0, Discount DECIMAL(18,2) NOT NULL DEFAULT 0,
    Tax DECIMAL(18,2) NOT NULL DEFAULT 0, GrandTotal DECIMAL(18,2) NOT NULL DEFAULT 0,
    PaidAmount DECIMAL(18,2) NOT NULL DEFAULT 0, Remarks TEXT,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS SalesInvoiceLines (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    SalesInvoiceId INTEGER NOT NULL REFERENCES SalesInvoices(Id) ON DELETE CASCADE,
    ProductId INTEGER NOT NULL REFERENCES Products(Id),
    ProductName TEXT NOT NULL,
    Quantity DECIMAL(18,2) NOT NULL DEFAULT 0,
    UnitPrice DECIMAL(18,2) NOT NULL DEFAULT 0,
    Tax DECIMAL(18,2) NOT NULL DEFAULT 0,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS PurchaseInvoices (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    InvoiceNumber TEXT NOT NULL UNIQUE, Date TEXT NOT NULL,
    SupplierId INTEGER NOT NULL REFERENCES Suppliers(Id),
    PaymentMode INTEGER NOT NULL DEFAULT 0,
    SubTotal DECIMAL(18,2) NOT NULL DEFAULT 0, Discount DECIMAL(18,2) NOT NULL DEFAULT 0,
    Tax DECIMAL(18,2) NOT NULL DEFAULT 0, GrandTotal DECIMAL(18,2) NOT NULL DEFAULT 0,
    PaidAmount DECIMAL(18,2) NOT NULL DEFAULT 0, Remarks TEXT,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS PurchaseInvoiceLines (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    PurchaseInvoiceId INTEGER NOT NULL REFERENCES PurchaseInvoices(Id) ON DELETE CASCADE,
    ProductId INTEGER NOT NULL REFERENCES Products(Id),
    ProductName TEXT NOT NULL,
    Quantity DECIMAL(18,2) NOT NULL DEFAULT 0,
    UnitPrice DECIMAL(18,2) NOT NULL DEFAULT 0,
    Tax DECIMAL(18,2) NOT NULL DEFAULT 0,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Payments (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    VoucherNumber TEXT NOT NULL, Date TEXT NOT NULL,
    Type INTEGER NOT NULL, PartyType INTEGER NOT NULL,
    CustomerId INTEGER REFERENCES Customers(Id),
    SupplierId INTEGER REFERENCES Suppliers(Id),
    StaffId INTEGER REFERENCES Staff(Id),
    BankAccount TEXT, Amount DECIMAL(18,2) NOT NULL DEFAULT 0, Remarks TEXT,
    CreatesAdvance INTEGER NOT NULL DEFAULT 0,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Returns (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    ReturnNumber TEXT NOT NULL UNIQUE, Date TEXT NOT NULL,
    Type INTEGER NOT NULL,
    CustomerId INTEGER REFERENCES Customers(Id),
    SupplierId INTEGER REFERENCES Suppliers(Id),
    OriginalInvoiceNumber TEXT,
    ProductId INTEGER NOT NULL REFERENCES Products(Id),
    ProductName TEXT NOT NULL,
    ReturnedQuantity DECIMAL(18,2) NOT NULL DEFAULT 0,
    UnitPrice DECIMAL(18,2) NOT NULL DEFAULT 0,
    RefundAmount DECIMAL(18,2) NOT NULL DEFAULT 0,
    Reason TEXT NOT NULL, Status INTEGER NOT NULL DEFAULT 0, Remarks TEXT,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Advances (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    CustomerId INTEGER NOT NULL REFERENCES Customers(Id),
    CustomerName TEXT NOT NULL,
    Amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    PaidAmount DECIMAL(18,2) NOT NULL DEFAULT 0,
    Date TEXT NOT NULL, Status INTEGER NOT NULL DEFAULT 0, Remarks TEXT,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Loans (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    CustomerId INTEGER NOT NULL REFERENCES Customers(Id),
    CustomerName TEXT NOT NULL,
    AdvanceAmount DECIMAL(18,2) NOT NULL DEFAULT 0,
    LoanAmount DECIMAL(18,2) NOT NULL DEFAULT 0,
    DateIssued TEXT NOT NULL, RepaymentDueDate TEXT NOT NULL,
    InstallmentPlan TEXT NOT NULL DEFAULT 'Monthly',
    PaidAmount DECIMAL(18,2) NOT NULL DEFAULT 0,
    Status INTEGER NOT NULL DEFAULT 0, Remarks TEXT,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS Expenses (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    Date TEXT NOT NULL, Category TEXT NOT NULL,
    Amount DECIMAL(18,2) NOT NULL DEFAULT 0, Remarks TEXT,
    PaidFrom INTEGER NOT NULL DEFAULT 0,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS SyncQueue (
    Id INTEGER PRIMARY KEY AUTOINCREMENT,
    EntityType TEXT NOT NULL, EntityId INTEGER NOT NULL,
    Operation TEXT NOT NULL, PayloadJson TEXT NOT NULL DEFAULT '{}',
    Synced INTEGER NOT NULL DEFAULT 0, SyncedAt TEXT, LastError TEXT,
    CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, IsDeleted INTEGER NOT NULL DEFAULT 0, IsDirty INTEGER NOT NULL DEFAULT 0
);
